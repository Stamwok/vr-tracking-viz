"""config.py — калибровка «камера относительно головы» (задача 05b; финал — 07c).

Единственный источник константы ``T_head_cam``: ``camera_model`` читает её отсюда и не
хардкодит числа, поэтому подбор (07b) и фиксация (07c) меняют только этот файл, а код
перевода мира в координаты камеры остаётся тем же.

Что здесь лежит: **поза камеры в системе координат головы**.

* ``HEAD_CAM_TRANSLATION_M`` — положение камеры в метрах: ``x`` вправо, ``y`` вверх,
  ``z`` вперёд (по взгляду). Заглушка 05b — 5 см вперёд от центра головы: камера шлема
  физически стоит перед лицом, но точное смещение из данных не выводится (экстринсики
  из header не согласуются с позой головы, см. ``docs/NOTES.md`` за 27.10).
* ``HEAD_CAM_ROTATION_RPY_DEG`` — ориентация камеры в градусах: ``yaw`` вокруг ``y``
  (вверх), ``pitch`` вокруг ``x`` (вправо), ``roll`` вокруг ``z`` (вперёд) в порядке
  поворотов ``R = R_y(yaw) · R_x(pitch) · R_z(roll)``. Заглушка — нули: камера смотрит
  туда же, куда голова.

Почему так: экстринсики из header'а непригодны напрямую — их поворот расходится с
``Head.pose`` на ~36° (перебор конвенций, см. заметки), поэтому поза камеры на кадр
восстанавливается из позы головы плюс эта константа. «Приблизительность» наложения —
осознанное допущение, оно описано в README.

Заглушечные значения меняются в 07b/07c; менять их можно и во время эксперимента —
``camera_model.head_cam_matrix()`` читает модуль при каждом вызове, поэтому достаточно
поправить число здесь (или подменить атрибут модуля в тесте/скрипте), не трогая код
перевода координат.
"""
from __future__ import annotations

#: Положение камеры в системе головы, метры: (вправо, вверх, вперёд).
#: Заглушка 05b — 5 см вперёд; финальное значение подбирается в 07b и фиксируется в 07c.
HEAD_CAM_TRANSLATION_M: tuple[float, float, float] = (0.0, 0.0, 0.05)

#: Ориентация камеры в системе головы, градусы: (yaw вокруг y, pitch вокруг x, roll вокруг z).
#: Заглушка 05b — камера смотрит как голова; финальное значение — 07c.
HEAD_CAM_ROTATION_RPY_DEG: tuple[float, float, float] = (0.0, 0.0, 0.0)
