"""config.py — зафиксированная калибровка «камера относительно головы» (задача 07c).

Единственный источник калибровочных констант: ``camera_model`` читает их отсюда при каждом
вызове и не хардкодит числа, поэтому пересчёт позы камеры (и весь рендер 08a) меняется
правкой этого файла, а не кода перевода мира в координаты камеры.

Значения получены в 07b перебором 24 собственных ротаций осей × 2 конвенций кватерниона ×
1331 положения камеры по эталону 07a (5 кадров, 45 суставов, допуск разметки ±50 px).
Победитель: **39 из 45** суставов в кадре и **все 39 — внутри рамок своих рук**, 0 чужих,
0 промахов, средняя ошибка **0.0 px**; следующий по счёту вариант — 184.6 px и 3 чужие руки.
Полное обоснование, отклонённые варианты и остаточные ошибки — ``docs/projection_notes.md``.

Что здесь лежит (система координат головы — как в данных, OpenXR: ``x`` вправо, ``y`` вверх,
``z`` **назад**, вперёд — ``−z``; статья XRoboToolkit SII 2026, §II-B):

* ``AXIS_CONVENTION`` — человекочитаемая запись осей камеры в осях головы: строка вида
  ``"+x −y −z"`` значит ``x_cam = +x_head``, ``y_cam = −y_head``, ``z_cam = −z_head``.
  Это не отдельная подгонка: строка обязана совпадать с тем, что даёт
  ``camera_model.axis_convention()`` из ``HEAD_CAM_ROTATION_RPY_DEG`` (проверка —
  ``camera_model.check_config()``), иначе конфиг считается рассогласованным.
* ``INVERT_QUAT`` — конвенция кватерниона головы: ``False`` = поза понимается как поворот
  головы в мире, ``True`` = как обратный поворот (вариант перебора 07b).
* ``Y_DOWN_FLIP`` — добавочный переворот ``y`` после ``T_head_cam`` (бывший флаг 05b
  ``opencv_conventions``; матрица ``F = diag(1, −1, 1)``). **Выключен**: «y вниз» уже даёт
  поворот камеры на 180° вокруг ``x``, отдельный переворот сделал бы из ориентации отражение
  (``det = −1``) и вернул бы ``z`` головы (назад) «вперёд» камеры — именно ошибка 05b.
* ``HEAD_CAM_ROTATION_RPY_DEG`` — ориентация камеры в системе головы, градусы:
  ``R = R_y(yaw) · R_x(pitch) · R_z(roll)`` (порядок задаёт ``camera_model.rotation_rpy``);
  финал — ``(0, 180, 0)``, т.е. поворот на 180° вокруг ``x`` головы.
* ``HEAD_CAM_TRANSLATION_M`` — положение камеры в системе головы, метры; финал — ``(0, 0, 0)``.
  Эталон 07a не различает смещение лучше ±2 см по ``x``/``y`` и ±2 см по ``z`` (шаг сетки 2 см
  на дистанции руки ≈31 px < допуска разметки ±50 px), поэтому берётся минимальная правка
  модели — камера в начале координат головы. Прежняя заглушка 05b «5 см вперёд» была на самом
  деле 5 см **назад**: ``z`` головы в данных смотрит назад, а на числа это уже не влияет.

Почему не экстринсики из header: их поворот расходится с ``Head.pose`` на ~36° даже при полном
переборе конвенций (метки времени отличаются лишь на 18.4 мс), похоже, они сняты кнопкой «Save
Camera Parameters» в другой позе. Поэтому они используются только как подсказка о базе глаз
(64 мм), а поза камеры берётся из позы головы плюс эта константа.

F_SCALE (масштаб фокуса) не вводится: интринсики из header согласуются со статьёй по FOV
(76.35° × 61.05° ≤ 0.003° расхождения), а общий зум не исправляет смещение проекции — остаток на
самой близкой кисти (k = 30, ≈70 px) объясняется допуском разметки, таймингом кадра и плато
смещения, а не масштабом.

Здесь же лежит **не пространственная** константа — поправка времени ``VIDEO_TIME_OFFSET_MS``
(задержка видеотракта). Она относится к синхронизации (``sync.pose_at_frame``), а не к камере, но
менять её надо тоже только здесь: и рендер (08a), и проверка калибровки (07c) обязаны брать время
кадра из одного места, иначе метрика перестанет описывать то, что видит пользователь. Значение
подобрано диагностикой ``src/drift_diag.py`` — см. docstring константы и ``docs/NOTES.md`` (29.10).

Менять калибровку — только здесь. ``camera_model`` перечитывает модуль на каждом вызове, так что
тесты и скрипты могут подменять атрибуты (``mock.patch.object``) без правки кода камеры; после
правки проверка: ``python src/calib_search.py data/trackingData_*.txt --verify-config``.
"""
from __future__ import annotations

#: Оси камеры в осях головы: ``"+x −y −z"`` (x вправо, y вниз, z вперёд).
#: Обязана совпадать с результатом ``camera_model.axis_convention()`` из поворота ниже.
AXIS_CONVENTION: str = "+x −y −z"

#: Конвенция кватерниона головы: False — поворот головы в мире (как в спецификации формата).
INVERT_QUAT: bool = False

#: Добавочный переворот ``y`` после T_head_cam (матрица ``diag(1, −1, 1)``).
#: Переворачивает только ``y`` и делает из ориентации отражение; в калибровке 07b отклонён.
Y_DOWN_FLIP: bool = False

#: Ориентация камеры в системе головы, градусы: (yaw вокруг y, pitch вокруг x, roll вокруг z).
#: ``(0, 180, 0)`` — поворот на 180° вокруг ``x`` головы: камера смотрит по ``+z``, ``y`` вниз.
HEAD_CAM_ROTATION_RPY_DEG: tuple[float, float, float] = (0.0, 180.0, 0.0)

#: Положение камеры в системе головы, метры (x вправо, y вверх, z назад — OpenXR).
#: Данные не различают смещение лучше ±2 см, поэтому принято нулевым (минимальная правка).
HEAD_CAM_TRANSLATION_M: tuple[float, float, float] = (0.0, 0.0, 0.0)

#: Задержка видеотракта относительно меток трекинга, мс: поза кадра берётся из ``t + Δ``.
#: **Отрицательная** — кадр показывает сцену, снятую раньше своей метки: чтобы попасть
#: скелетом на кисть, позу надо брать из прошлого. Значение подобрано диагностикой
#: ``src/drift_diag.py`` (2026-10-29, доработка 08a): на 50 самых быстрых кадрах средняя
#: ошибка наложения падает с ≈77 до ≈30 px при сдвиге −140 мс и с ≈40 до ≈1 px по кисти и
#: запястью; визуальная сверка на четырёх быстрых кадрах даёт −80…−140 мс (медиана −100).
#: Скан по третям записи даёт те же −100…−140 мс — значит это не дрейф, а постоянная
#: задержка; причины из данных неразличимы (латентность камеры/кодера или задержка
#: hand-трекинга) и записаны в ``docs/NOTES.md``. Точность ≈ ±40 мс.
VIDEO_TIME_OFFSET_MS: float = -100.0
